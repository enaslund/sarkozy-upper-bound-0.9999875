#!/usr/bin/env python3
"""Build the manuscript in a temporary directory, with strict final log checks.

Usage: python3 -B paper/build.py [--output-dir DIR] [--keep]
The build uses only the TeX/BibTeX/figure closure under paper/.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

PAPER = Path(__file__).resolve().parent
ROOT = PAPER.parent
REJECT = ('Overfull', 'undefined references', 'undefined citations', 'There were undefined',
          'multiply defined', 'Label(s) may have changed', 'Rerun to get',
          'destination with the same identifier')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def strip(text):
    return '\n'.join(re.sub(r'(?<!\\)%.*$', '', line) for line in text.splitlines())


def closure():
    seen, pending = {}, [PAPER/'main.tex', PAPER/'figures'/'dependency_graph.tex']
    while pending:
        path = pending.pop().resolve()
        if path in seen:
            continue
        if PAPER not in path.parents:
            raise SystemExit(f'build: input outside paper/: {path}')
        if not path.is_file():
            raise SystemExit(f'build: missing input {path.relative_to(ROOT)}')
        seen[path] = sha(path)
        if path.suffix != '.tex':
            continue
        text = strip(path.read_text())
        for name in re.findall(r'\\(?:input|include)\{([^{}]+)\}', text):
            target = PAPER/name
            pending.append(target if target.suffix == '.tex' else target.with_name(target.name+'.tex'))
        for names in re.findall(r'\\bibliography\{([^{}]+)\}', text):
            pending += [PAPER/(n.strip()+'.bib') for n in names.split(',')]
        for name in re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^{}]+)\}', text):
            if name != 'figures/dependency_graph.pdf':   # generated by the first pass
                pending.append(PAPER/name)
    return seen


def run_pass(args, work):
    """Every typesetting pass, including a label-settling rerun, must succeed."""
    env = dict(os.environ, SOURCE_DATE_EPOCH='1794268800', FORCE_SOURCE_DATE='1')
    run = subprocess.run(args, cwd=work, env=env, capture_output=True, text=True, errors='replace')
    if run.returncode:
        # The failed command's output is more useful than a possibly stale main.log.
        raise SystemExit(f'build: {" ".join(args)} failed\n{run.stdout[-6000:]}\n{run.stderr[-1000:]}')


def build(output_dir=None, keep=False):
    files = closure()
    work = Path(tempfile.mkdtemp(prefix='sarkozy-paper-build-'))
    try:
        for path in files:
            if sha(path) != files[path]:
                raise SystemExit(f'build: input changed before copying: {path.relative_to(ROOT)}')
            target = work/path.relative_to(PAPER)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            if sha(target) != files[path]:
                raise SystemExit(f'build: copied input differs: {path.relative_to(ROOT)}')
        passes = [['pdflatex', '-interaction=nonstopmode', '-halt-on-error', '-output-directory', 'figures',
                   'figures/dependency_graph.tex'],
                  ['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'main.tex'],
                  ['bibtex', 'main'],
                  ['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'main.tex'],
                  ['pdflatex', '-interaction=nonstopmode', '-halt-on-error', 'main.tex']]
        for args in passes:
            run_pass(args, work)
        log = (work/'main.log').read_text(errors='replace')
        for _ in range(2):   # long documents may need one or two more passes to settle labels
            if 'Label(s) may have changed' not in log and 'Rerun to get' not in log:
                break
            run_pass(passes[-1], work)
            log = (work/'main.log').read_text(errors='replace')
        problems = [line for line in log.splitlines() if any(r in line for r in REJECT)]
        if problems:
            raise SystemExit('build: rejected log lines:\n' + '\n'.join(problems[:40]))
        if closure() != files:
            raise SystemExit('build: manuscript inputs changed during typesetting')
        pdf, fig = work/'main.pdf', work/'figures'/'dependency_graph.pdf'
        info = subprocess.run(['pdfinfo', str(pdf)], capture_output=True, text=True).stdout
        pages = int(re.search(r'Pages:\s+(\d+)', info).group(1))
        out = Path(output_dir).resolve() if output_dir else PAPER
        (out/'figures').mkdir(parents=True, exist_ok=True)
        shutil.copy2(pdf, out/'main.pdf')
        shutil.copy2(fig, out/'figures'/'dependency_graph.pdf')
        record = dict(status='PASS', pages=pages, pdf_sha256=sha(out/'main.pdf'),
                      inputs_unchanged=True,
                      closure={str(p.relative_to(ROOT)): h for p, h in sorted(files.items())})
        if output_dir:
            (out/'build_record.json').write_text(json.dumps(record, indent=1)+'\n')
        print(json.dumps(dict(record, closure=len(files)), indent=1))
    finally:
        if keep:
            print('build tree kept at', work, file=sys.stderr)
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--keep', action='store_true', help='Keep the temporary build tree.')
    args = parser.parse_args()
    build(args.output_dir, keep=args.keep)
