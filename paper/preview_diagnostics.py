#!/usr/bin/env python3
"""Prepare controlled tests of Hexagon's PDF preview processing.

--verify builds the current export and three diagnostic files in clean temporary
directories, compares the complete manuscript, then installs sources and a
verification receipt in preview-diagnostics/. Requires pdflatex, pdftotext and
the Python package pikepdf. --check checks saved sources and receipt hashes only.
Neither operation calls Hexagon or modifies the canonical manuscript.
"""

import argparse
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

import build
from submission import REFERENCE

PAPER = Path(__file__).resolve().parent
OUTPUT = PAPER / "preview-diagnostics"


def digest(raw):
    return sha256(raw).hexdigest()


def sources(original):
    static = original
    replacements = {
        r"\usepackage[hypertexnames=false,":
            r"\usepackage[bookmarks=false,pageanchor=false,pdfpagelabels=false,hypertexnames=false,",
        r"\begin{document}": "\\begin{document}\n\\begin{NoHyper}",
        r"\end{document}": "\\end{NoHyper}\n\\end{document}",
    }
    for old, new in replacements.items():
        if static.count(old) != 1:
            raise ValueError(f"Expected exactly one source marker: {old}")
        static = static.replace(old, new)
    static = (
        "% Diagnostic export generated by paper/preview_diagnostics.py.\n"
        "% Complete manuscript without PDF navigation; hosted acceptance unconfirmed.\n"
        + static
    )
    result = {"static": static}
    for count in (1, 603):
        result[f"pages-{count}"] = r"""% Diagnostic only: not the manuscript and not for final submission.
\pdfminorversion=4
\pdfobjcompresslevel=0
\documentclass{article}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\begin{document}
\newcount\DiagnosticPage
\DiagnosticPage=1
\loop
\noindent Hexagon preview diagnostic. Page \the\DiagnosticPage.
\par This file tests PDF preview processing of a simple document.
\[1+1=2\]
\clearpage
\advance\DiagnosticPage by 1
\ifnum\DiagnosticPage<""" + str(count + 1) + r"""
\repeat
\end{document}
"""
    return result


def run(args, work):
    result = subprocess.run(
        args, cwd=work, capture_output=True, text=True, errors="replace",
        env=dict(os.environ, SOURCE_DATE_EPOCH="1794268800", FORCE_SOURCE_DATE="1"),
    )
    if result.returncode:
        raise ValueError(f"{args[0]} failed:\n{result.stdout[-4000:]}\n{result.stderr[-2000:]}")
    return result.stdout


def compile_source(text, work):
    import pikepdf

    work.mkdir()
    (work / "output").mkdir()
    (work / "hexagon-standalone.tex").write_text(text)
    command = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "-file-line-error",
               "-no-shell-escape", "-recorder", "-jobname=paper", "-output-directory=output",
               "hexagon-standalone.tex"]
    for passes in range(1, 6):
        run(command, work)
        log = (work / "output/paper.log").read_text(errors="replace")
        normalized = " ".join(log.split())
        if any(word in normalized for word in
               ("ignored error:", "Infinite glue shrinkage", "multiply defined")):
            raise ValueError(f"{work.name}: primitive diagnostic or duplicate label on pass {passes}")
        if passes >= 2 and not any(word in log for word in
                                  ("Label(s) may have changed", "Rerun to get",
                                   "Table widths have changed")):
            break
    if any(word in log for word in build.REJECT):
        raise ValueError(f"{work.name}: final log failed manuscript checks")
    warnings = build.warning_summary(log)
    if warnings["package_warnings"]:
        raise ValueError(f"{work.name}: unresolved package warnings")
    path = work / "output/paper.pdf"
    with pikepdf.Pdf.open(path) as pdf:
        issues = pdf.check_pdf_syntax()
        if issues:
            raise ValueError(f"{work.name}: PDF syntax check failed: {issues}")
        annotations = sum(len(page.get("/Annots", [])) for page in pdf.pages)
        record = dict(pages=len(pdf.pages), pdf_version=str(pdf.pdf_version),
                      pdf_bytes=path.stat().st_size, pdf_sha256=digest(path.read_bytes()),
                      pdf_objects=len(pdf.objects), annotations=annotations,
                      outlines_present="/Outlines" in pdf.Root,
                      qpdf_syntax_issues=issues)
    record.update(source_sha256=digest(text.encode()), source_bytes=len(text.encode()),
                  pdflatex_passes=passes, warnings=warnings,
                  primitive_diagnostics_all_passes=0, multiply_defined_labels_all_passes=0)
    return record, log


def verify(original, variants):
    import pikepdf

    with tempfile.TemporaryDirectory(prefix="hexagon-preview-diagnostics-") as name:
        work = Path(name)
        records = {}
        for variant, text in {"linked": original, **variants}.items():
            print(f"Compiling {variant} ...", flush=True)
            records[variant], log = compile_source(text, work / variant)
            if variant == "linked":
                toolchain = dict(
                    engine=run(["pdflatex", "--version"], work).splitlines()[0],
                    latex=re.search(r"LaTeX2e <([^>]+)>", log)[1],
                    l3=re.search(r"L3 programming layer <([^>]+)>", log)[1],
                    longtable=re.search(r"Package: longtable ([^\n]+)", log)[1],
                    qpdf=pikepdf.__libqpdf_version__,
                    text_extractor="pdftotext -raw",
                )
        extracted, references = [], []
        for variant in ("linked", "static"):
            compiled = work / variant / "output"
            text = run(["pdftotext", "-raw", str(compiled / "paper.pdf"), "-"], work)
            extracted.append(re.sub(r"\s+", "", text))
            references.append(REFERENCE.findall((compiled / "paper.aux").read_text()))
        if extracted[0] != extracted[1] or not references[0] or references[0] != references[1]:
            raise ValueError("Static diagnostic changed manuscript text, a reference or a citation")
        if records["static"]["pages"] != records["linked"]["pages"]:
            raise ValueError("Static diagnostic changed the manuscript page count")
        if records["static"]["annotations"] or records["static"]["outlines_present"]:
            raise ValueError("Static diagnostic still contains PDF navigation")
        for count in (1, 603):
            if records[f"pages-{count}"]["pages"] != count:
                raise ValueError("Page-count diagnostic has the wrong number of pages")
        return dict(
            format=1, status="PASS_LOCAL_CHECKS_HOSTED_ACCEPTANCE_UNKNOWN",
            generator_sha256=digest(Path(__file__).read_bytes()),
            original_source="hexagon-standalone.tex", toolchain=toolchain,
            compilation=dict(jobname="paper", shell_escape=False,
                             clean_directory_per_variant=True, separate_output_directory=True,
                             custom_hexagon_format=False),
            comparison=dict(identical_text_ignoring_whitespace=True,
                            text_extraction="pdftotext -raw; remove whitespace only",
                            identical_labels_and_citations=True,
                            labels_and_citations=len(references[0]), identical_page_count=True),
            builds=records,
        )


def check(original, variants):
    record = json.loads((OUTPUT / "verification.json").read_text())
    if record["generator_sha256"] != digest(Path(__file__).read_bytes()):
        raise ValueError("Diagnostic generator changed; rerun --verify")
    if record["builds"]["linked"]["source_sha256"] != digest(original.encode()):
        raise ValueError("Canonical export changed; rerun --verify")
    for variant, text in variants.items():
        if (OUTPUT / variant / "hexagon-standalone.tex").read_text() != text:
            raise ValueError(f"Diagnostic source changed: {variant}")
        if record["builds"][variant]["source_sha256"] != digest(text.encode()):
            raise ValueError(f"Verification receipt does not match {variant}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--verify", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    original = (PAPER / "hexagon-standalone.tex").read_text()
    variants = sources(original)
    if args.verify:
        record = verify(original, variants)
        if original != (PAPER / "hexagon-standalone.tex").read_text():
            raise ValueError("Canonical export changed during verification")
        for variant, text in variants.items():
            path = OUTPUT / variant / "hexagon-standalone.tex"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        (OUTPUT / "verification.json").write_text(json.dumps(record, indent=2) + "\n")
    check(original, variants)
    print("PASS: diagnostic sources and verification hashes match; hosted acceptance remains unknown.")


if __name__ == "__main__":
    main()
