"""Generate and verify the single-file, two-pass submission export.

The editable manuscript remains in main.tex and sections/. The export inlines
those inputs, the typeset bibliography and the dependency diagram. Reference
data from a clean build is used only to initialize an otherwise empty build;
ordinary auxiliary files take over on subsequent passes.
"""
from hashlib import sha256
from pathlib import Path
import re

import build


INPUT = re.compile(r"(?m)^\\input\{([^{}]+)\}[ \t]*(?:\n|$)")
REFERENCE = re.compile(r"(?m)^\\(?:newlabel|bibcite).*$")


def flatten(paper, name="main.tex", stack=()):
    path = (paper / name).resolve()
    if not path.suffix:
        path = path.with_suffix(".tex")
    if paper.resolve() not in path.parents or path in stack:
        raise ValueError("Submission input escapes paper/ or forms a cycle")

    def expand(match):
        content = flatten(paper, match[1], (*stack, path))
        # Preserve the space left by the original input command at EOF. In a
        # paragraph this can change line breaking even when all words agree.
        return (f"% Begin {match[1]}\n" + content
                + ("" if content.endswith("\n") else "\n")
                + "\\space\n" + f"% End {match[1]}\n")

    return INPUT.sub(expand, path.read_text())


def reference_seed(compiled):
    aux = (compiled / "main.aux").read_text()
    # Table-width definitions span multiple indented lines in the aux file.
    entries = "".join(re.findall(
        r"(?m)^(?:\\newlabel|\\bibcite|\\gdef \\LT@).*?(?=^\\|\Z)", aux, re.S))
    entries = "\n".join(line.rstrip() for line in entries.splitlines()) + "\n"
    toc = (compiled / "main.toc").read_text()
    return r"""% Initial reference data from the independently compiled manuscript.
% The normal aux/toc files are regenerated; these values are not frozen.
\begin{filecontents*}[noheader]{\jobname.toc}
""" + toc + r"""\end{filecontents*}
\makeatletter
\AtBeginDocument{%
  \@ifundefined{HexagonAuxReady}{%
    \@ifundefined{r@thm:main}{%
""" + entries + r"""    }{}%
  }{}%
  \immediate\write\@auxout{\string\gdef\string\HexagonAuxReady{}}%
}
\makeatother
"""


def source(paper, compiled):
    text = flatten(paper)
    # amsart's bibliographystyle command also selects unbracketed list labels.
    # Preserve those effects without requesting a BibTeX job.
    text = text.replace(r"\bibliographystyle{amsplain}", r"""\makeatletter
\def\@biblabel#1{\@defaultbiblabelstyle{#1}}%
\def\bibsetup{}%
\makeatother""")
    text = text.replace(r"\bibliography{references}",
                        (compiled / "main.bbl").read_text())

    figure = (paper / "figures/dependency_graph.tex").read_text()
    if r"\documentclass[tikz,border=4pt]{standalone}" not in figure:
        raise ValueError("Update the inline diagram wrapper for the new figure class")
    drawing = figure.split(r"\begin{document}", 1)[1].split(r"\end{document}", 1)[0].strip()
    libraries = re.findall(r"\\usetikzlibrary\{[^{}]+\}", figure)
    text = text.replace(r"\usepackage{tikz}",
                        r"\usepackage{tikz}" + "\n" + "\n".join(libraries))
    # Match the standalone figure's 10pt article fonts and 4pt border. Use
    # local engine settings, not microtype's persistent font configuration.
    inline = r"""\begingroup
\pdfprotrudechars=0 \pdfadjustspacing=0\relax%
\renewcommand{\small}{\fontsize{9}{11}\selectfont}%
\renewcommand{\footnotesize}{\fontsize{8}{9.5}\selectfont}%
\fontsize{10}{12}\selectfont
\setlength{\fboxsep}{4pt}\setlength{\fboxrule}{0pt}%
\resizebox{\textwidth}{!}{\fbox{%
""" + drawing + r"""%
}}%
\endgroup"""
    text = text.replace(r"\includegraphics[width=\textwidth]{figures/dependency_graph.pdf}", inline)
    text = text.replace(r"\begin{document}",
                        reference_seed(compiled) + "\n" + r"\begin{document}", 1)
    if re.search(r"\\(?:input|include|includegraphics|bibliography|bibliographystyle)\b",
                 build.strip(text)):
        raise ValueError("An external manuscript dependency remains in the export")
    return ("% Generated by paper/package_publication.py; edit the modular sources.\n"
            "% All manuscript text, bibliography and the vector diagram are included.\n"
            "% Compile with pdflatex (no shell escape), or latexmk -pdf.\n" + text)


def verify(paper, compiled, work, command):
    """Compile from one file, under Hexagon's job-name/output-dir convention."""
    work.mkdir()
    (work / "output").mkdir()
    exported = source(paper, compiled)
    (work / "main.tex").write_text(exported)
    latex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
             "-file-line-error", "-no-shell-escape", "-recorder",
             "-jobname=paper", "-output-directory=output", "main.tex"]
    for passes in range(1, 6):
        command(latex, work)
        log = (work / "output/paper.log").read_text(errors="replace")
        # Always test a pass that reads the newly generated auxiliary files.
        if passes >= 2 and not any(term in log for term in
                                  ("Label(s) may have changed", "Rerun to get",
                                   "Table widths have changed")):
            break
    problems = [line for line in log.splitlines() if any(t in line for t in build.REJECT)]
    if problems:
        raise ValueError("Standalone build failed final log checks: " + "\n".join(problems[:20]))
    pdf = work / "output/paper.pdf"
    # Inlining the diagram combines font subsets, which can change Poppler's
    # spatial text-order heuristics. Compare the actual content-stream order.
    original_text = command(["pdftotext", "-raw", str(compiled / "main.pdf"), "-"], work)
    exported_text = command(["pdftotext", "-raw", str(pdf), "-"], work)
    if original_text != exported_text:
        raise ValueError("Standalone export changed the rendered manuscript text")
    original_refs = REFERENCE.findall((compiled / "main.aux").read_text())
    exported_refs = REFERENCE.findall((work / "output/paper.aux").read_text())
    if original_refs != exported_refs:
        raise ValueError("Standalone export changed a label, page reference or citation")
    pages = int(re.search(r"Pages:\s+(\d+)", command(["pdfinfo", str(pdf)], work)).group(1))
    return dict(source="hexagon-standalone.tex", sha256=sha256(exported.encode()).hexdigest(),
                bytes=len(exported.encode()), pages=pages, pdflatex_passes=passes,
                bibliography_inlined=True, diagram_inlined=True,
                reference_seed="first build only; regenerated aux/toc take precedence",
                verification=dict(clean_final_log=True, identical_rendered_text=True,
                                  text_extraction="pdftotext -raw",
                                  identical_labels_and_citations=True,
                                  labels_and_citations=len(exported_refs), jobname="paper",
                                  separate_output_directory=True, shell_escape=False),
                export_script_sha256=sha256(Path(__file__).read_bytes()).hexdigest())
