"""Generate and verify the single-file, two-pass submission export.

The editable manuscript remains in main.tex and sections/. The export inlines
those inputs, the typeset bibliography and the dependency diagram. Reference
data from a clean build is used only to initialize an otherwise empty build;
ordinary auxiliary files take over on subsequent passes.
"""
from hashlib import sha256
from pathlib import Path
import json
import re

import pikepdf

import build


INPUT = re.compile(r"(?m)^\\input\{([^{}]+)\}[ \t]*(?:\n|$)")
REFERENCE = re.compile(r"(?m)^\\(?:newlabel|bibcite).*$")


def flatten(paper, name="main.tex", stack=()):
    path = (paper / name).resolve()
    if not path.suffix:
        path = path.with_suffix(".tex")
    if paper.resolve() not in path.parents or path in stack:
        raise ValueError("Submission input escapes paper/ or forms a cycle")

    def expand(match):
        content = flatten(paper, match[1], (*stack, path))
        # Preserve the space left by the original input command at EOF. In a
        # paragraph this can change line breaking even when all words agree.
        return (f"% Begin {match[1]}\n" + content
                + ("" if content.endswith("\n") else "\n")
                + "\\space\n" + f"% End {match[1]}\n")

    return INPUT.sub(expand, path.read_text())


def reference_seed(compiled):
    aux = (compiled / "main.aux").read_text()
    # Table-width definitions span multiple indented lines in the aux file.
    entries = "".join(re.findall(
        r"(?m)^(?:\\newlabel|\\bibcite|\\gdef \\LT@).*?(?=^\\|\Z)", aux, re.S))
    entries = "\n".join(line.rstrip() for line in entries.splitlines()) + "\n"
    # amsart initializes these dimensions before our begin-document hook.
    # Set their cached values directly instead of redefining existing labels.
    entries = re.sub(r"(?m)^\\newlabel\{(tocindent-?\d+)\}\{([^{}]+)\}$",
                     lambda m: rf"\expandafter\gdef\csname r@{m[1]}\endcsname{{{m[2]}}}",
                     entries)
    toc = (compiled / "main.toc").read_text()
    return r"""% Initial reference data from the independently compiled manuscript.
% The normal aux/toc files are regenerated; these values are not frozen.
\begin{filecontents*}[noheader]{\jobname.toc}
""" + toc + r"""\end{filecontents*}
\makeatletter
\AtBeginDocument{%
  \@ifundefined{HexagonAuxReady}{%
    \@ifundefined{r@thm:main}{%
""" + entries + r"""    }{}%
  }{}%
  \immediate\write\@auxout{\string\gdef\string\HexagonAuxReady{}}%
}
\makeatother
"""


def source(paper, compiled):
    text = flatten(paper)
    # amsart's bibliographystyle command also selects unbracketed list labels.
    # Preserve those effects without requesting a BibTeX job.
    text = text.replace(r"\bibliographystyle{amsplain}", r"""\makeatletter
\def\@biblabel#1{\@defaultbiblabelstyle{#1}}%
\def\bibsetup{}%
\makeatother""")
    text = text.replace(r"\bibliography{references}",
                        (compiled / "main.bbl").read_text())

    figure = (paper / "figures/dependency_graph.tex").read_text()
    if r"\documentclass[tikz,border=4pt]{standalone}" not in figure:
        raise ValueError("Update the inline diagram wrapper for the new figure class")
    drawing = figure.split(r"\begin{document}", 1)[1].split(r"\end{document}", 1)[0].strip()
    libraries = re.findall(r"\\usetikzlibrary\{[^{}]+\}", figure)
    text = text.replace(r"\usepackage{tikz}",
                        r"\usepackage{tikz}" + "\n" + "\n".join(libraries))
    # Match the standalone figure's 10pt article fonts and 4pt border. Use
    # local engine settings, not microtype's persistent font configuration.
    inline = r"""\begingroup
\pdfprotrudechars=0 \pdfadjustspacing=0\relax%
\renewcommand{\small}{\fontsize{9}{11}\selectfont}%
\renewcommand{\footnotesize}{\fontsize{8}{9.5}\selectfont}%
\fontsize{10}{12}\selectfont
\setlength{\fboxsep}{4pt}\setlength{\fboxrule}{0pt}%
\resizebox{\textwidth}{!}{\fbox{%
""" + drawing + r"""%
}}%
\endgroup"""
    text = text.replace(r"\includegraphics[width=\textwidth]{figures/dependency_graph.pdf}", inline)
    text = text.replace(r"\begin{document}",
                        reference_seed(compiled) + "\n" + r"\begin{document}", 1)
    # Inherit the manuscript's hyperref configuration, including its links,
    # bookmarks and compatibility fixes. The older navigation-free export is
    # preserved separately as hexagon-standalone-basic-file.tex.
    if re.search(r"\\(?:input|include|includegraphics|bibliography|bibliographystyle)\b",
                 build.strip(text)):
        raise ValueError("An external manuscript dependency remains in the export")
    return ("% Generated by paper/package_publication.py; edit the modular sources.\n"
            "% Hexagon upload: full manuscript PDF navigation; Unicode delimiter mappings included.\n"
            "% All manuscript text, bibliography and the vector diagram are included.\n"
            "% Compile with pdflatex (no shell escape), or latexmk -pdf.\n" + text)


def navigation(document):
    """Resolve every link and bookmark for comparison with the reading copy.

    Object numbers can differ after inlining the diagram. Compare named
    destinations by their target page, and links by their source page and
    target, rather than by PDF object identity.
    """
    pages = {page.obj.objgen: i + 1 for i, page in enumerate(document.pages)}

    def target_page(destination):
        if isinstance(destination, pikepdf.Dictionary):
            destination = destination.D
        if not isinstance(destination, pikepdf.Array) or not destination:
            raise ValueError("Invalid PDF destination")
        return pages[destination[0].objgen]

    destinations = {}
    names = document.Root.get("/Names", {})
    if "/Dests" in names:
        destinations = {name: target_page(value) for name, value in
                        pikepdf.NameTree(names["/Dests"]).items()}

    def action(item):
        if "/Dest" in item:
            kind, target = "/GoTo", item.Dest
        else:
            link = item.A
            kind = str(link.S)
            target = link.D if kind == "/GoTo" else link.URI
        if kind == "/GoTo":
            if isinstance(target, pikepdf.Array):
                return (kind, None, target_page(target))
            name = str(target)
            return (kind, name, destinations[name])
        if kind != "/URI":
            raise ValueError(f"Unexpected PDF link action: {kind}")
        return (kind, str(target))

    links = []
    for page_number, page in enumerate(document.pages, 1):
        for annotation in page.get("/Annots", []):
            if annotation.get("/Subtype") != pikepdf.Name.Link:
                raise ValueError("Unexpected non-link PDF annotation")
            links.append((page_number, *action(annotation)))
    outlines, seen = [], set()

    def visit(item, depth=0):
        while item is not None:
            if item.objgen in seen:
                raise ValueError("Cycle in PDF bookmarks")
            seen.add(item.objgen)
            outlines.append((depth, str(item.Title), *action(item)))
            visit(item.get("/First"), depth + 1)
            item = item.get("/Next")

    if "/Outlines" in document.Root:
        visit(document.Root.Outlines.get("/First"))
    return dict(destinations=destinations, links=links, outlines=outlines)


def verify(paper, compiled, work, command):
    """Compile from one file, under Hexagon's job-name/output-dir convention."""
    work.mkdir()
    (work / "output").mkdir()
    exported = source(paper, compiled)
    (work / "hexagon-standalone.tex").write_text(exported)
    latex = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
             "-file-line-error", "-no-shell-escape", "-recorder",
             "-jobname=paper", "-output-directory=output", "hexagon-standalone.tex"]
    for passes in range(1, 6):
        command(latex, work)
        log = (work / "output/paper.log").read_text(errors="replace")
        # These nonfatal primitive diagnostics can still trip hosted preview
        # log parsers. Reject them on every pass, including the seeded first run.
        normalized_log = " ".join(log.split())
        if any(term in normalized_log for term in
               ("ignored error:", "Infinite glue shrinkage", "multiply defined")):
            raise ValueError(f"Standalone pass {passes} contains a primitive diagnostic or duplicate label")
        # Always test a pass that reads the newly generated auxiliary files.
        if passes >= 2 and not any(term in log for term in
                                  ("Label(s) may have changed", "Rerun to get",
                                   "Table widths have changed")):
            break
    problems = [line for line in log.splitlines() if any(t in line for t in build.REJECT)]
    if problems:
        raise ValueError("Standalone build failed final log checks: " + "\n".join(problems[:20]))
    pdf = work / "output/paper.pdf"
    # Inlining the diagram combines font subsets, which can change Poppler's
    # spatial text-order heuristics.
    # Compare content-stream text after removing whitespace only.
    original_text = command(["pdftotext", "-raw", str(compiled / "main.pdf"), "-"], work)
    exported_text = command(["pdftotext", "-raw", str(pdf), "-"], work)
    if re.sub(r"\s+", "", original_text) != re.sub(r"\s+", "", exported_text):
        raise ValueError("Standalone export changed the rendered manuscript text")
    original_refs = REFERENCE.findall((compiled / "main.aux").read_text())
    exported_refs = REFERENCE.findall((work / "output/paper.aux").read_text())
    if original_refs != exported_refs:
        raise ValueError("Standalone export changed a label, page reference or citation")
    info = command(["pdfinfo", str(pdf)], work)
    pages = int(re.search(r"Pages:\s+(\d+)", info).group(1))
    pdf_version = re.search(r"PDF version:\s+(\S+)", info).group(1)
    if pdf_version != "1.4":
        raise ValueError("Submission PDF must retain the PDF 1.4 compatibility setting")
    with pikepdf.Pdf.open(pdf) as document:
        issues = document.check_pdf_syntax()
        annotations = sum(len(page.get("/Annots", [])) for page in document.pages)
        outlines = "/Outlines" in document.Root
        if issues:
            raise ValueError("Submission PDF has syntax issues")
        exported_navigation = navigation(document)
        with pikepdf.Pdf.open(compiled / "main.pdf") as original:
            if exported_navigation != navigation(original):
                raise ValueError("Standalone export changed manuscript links, bookmarks or target pages")
        if not annotations or not exported_navigation["outlines"]:
            raise ValueError("Submission PDF lost its links or bookmarks")
        objects = len(document.objects)
    navigation_record = dict(
        matches_main_pdf=True, all_internal_targets_resolved=True,
        links=annotations,
        internal_links=sum(link[1] == "/GoTo" for link in exported_navigation["links"]),
        external_links=sum(link[1] == "/URI" for link in exported_navigation["links"]),
        bookmarks=len(exported_navigation["outlines"]),
        named_destinations=len(exported_navigation["destinations"]),
        sha256=sha256(json.dumps(exported_navigation, sort_keys=True).encode()).hexdigest())
    return dict(source="hexagon-standalone.tex", profile="rich", sha256=sha256(exported.encode()).hexdigest(),
                pdf="hexagon-standalone.pdf", pdf_sha256=sha256(pdf.read_bytes()).hexdigest(),
                pdf_bytes=pdf.stat().st_size, pdf_objects=objects,
                annotations=annotations, outlines_present=outlines, qpdf_syntax_issues=issues,
                bytes=len(exported.encode()), pages=pages, pdflatex_passes=passes,
                pdf_version=pdf_version, warnings=build.warning_summary(log),
                bibliography_inlined=True, diagram_inlined=True,
                reference_seed="first build only; regenerated aux/toc take precedence",
                verification=dict(clean_final_log=True, identical_text_ignoring_whitespace=True,
                                  navigation=navigation_record,
                                  structured_text=build.check_pdf_text(pdf, pages),
                                  text_extraction="pdftotext -raw; remove whitespace only",
                                  identical_labels_and_citations=True,
                                  labels_and_citations=len(exported_refs), jobname="paper",
                                  separate_output_directory=True, shell_escape=False,
                                  primitive_diagnostics_all_passes=0,
                                  multiply_defined_labels_all_passes=0),
                toolchain=dict(engine=command(["pdflatex", "--version"], work).splitlines()[0],
                               qpdf=pikepdf.__libqpdf_version__,
                               latex=re.search(r"LaTeX2e <([^>]+)>", log).group(1),
                               l3=re.search(r"L3 programming layer <([^>]+)>", log).group(1),
                               longtable=re.search(r"Package: longtable ([^\n]+)", log).group(1)),
                export_script_sha256=sha256(Path(__file__).read_bytes()).hexdigest())
